#!/usr/bin/env python3
"""Generate glue/overlay_font.h: an 8x16 anti-aliased bitmap of ASCII 32..126 from
DejaVu Sans Mono Bold (Bitstream Vera / DejaVu licence: free to use and embed).
Usage: gen_overlay_font.py /usr/share/fonts/truetype/dejavu/DejaVuSansMono-Bold.ttf out.h"""
import sys
from PIL import Image, ImageDraw, ImageFont

W, H = 8, 16
font = ImageFont.truetype(sys.argv[1], 13)
asc, desc = font.getmetrics()
rows = []
for c in range(32, 127):
    im = Image.new("L", (W, H), 0)
    d = ImageDraw.Draw(im)
    d.text((0, (H - asc - desc) // 2 + 1), chr(c), fill=255, font=font)
    rows.append(bytes(im.getdata()))
with open(sys.argv[2], "w") as f:
    f.write("// Generated by tools/gen_overlay_font.py from DejaVu Sans Mono Bold (DejaVu fonts licence).\n")
    f.write("// ASCII 32..126, %dx%d pixels, 8-bit coverage, row-major.\n#pragma once\n#include <cstdint>\n\n" % (W, H))
    f.write("namespace d1::overlay_font {\nconstexpr int kWidth = %d, kHeight = %d, kFirst = 32, kLast = 126;\n" % (W, H))
    f.write("constexpr uint8_t kGlyphs[%d][%d] = {\n" % (len(rows), W * H))
    for r in rows:
        f.write("    {" + ",".join(str(b) for b in r) + "},\n")
    f.write("};\n}  // namespace d1::overlay_font\n")
