#!/usr/bin/env python3
"""Turn raw Ghidra exports into the committed analysis/<build>/ layout.

    python3 tools/ghidra/publish.py <build-id> <raw-dir>

<raw-dir> holds what imports.py, unwind.py, ExportAll.java and Decompile.java wrote:
  imports.tsv unwind.tsv functions.tsv callgraph.tsv symbols.tsv strings.tsv types.h disasm.jsonl decomp-*.jsonl

There is no build with symbols, so nothing says which source file a function came from. Pseudocode and
disassembly are grouped by 64 KB address block (pseudocode/00350000.c holds 00350000-0035ffff), functions in
address order. To find a function, take the first four digits of its address.

Generated output only: never hand-edit what this writes.
"""
import csv
import json
import shutil
import sys
from collections import defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
csv.field_size_limit(1 << 30)


def read_tsv(path):
    if not path.exists():
        return []
    with open(path, newline="") as f:
        return list(csv.DictReader(f, delimiter="\t", quoting=csv.QUOTE_NONE))


def main():
    build, raw = sys.argv[1], Path(sys.argv[2])
    out = ROOT / "analysis" / build

    gdir = out / "ghidra"
    gdir.mkdir(parents=True, exist_ok=True)
    for name in ("functions.tsv", "callgraph.tsv", "symbols.tsv", "strings.tsv", "types.h"):
        if (raw / name).exists():
            shutil.copyfile(raw / name, gdir / name)
    for name in ("imports.tsv", "unwind.tsv"):
        if (raw / name).exists():
            shutil.copyfile(raw / name, out / name)
    unwind = {r["va"]: r["size"] for r in read_tsv(raw / "unwind.tsv")}
    for log in raw.glob("*.log"):
        (out / "logs").mkdir(parents=True, exist_ok=True)
        shutil.copyfile(log, out / "logs" / log.name)

    ghidra = read_tsv(raw / "functions.tsv")
    decomp = {}
    for shard in sorted(raw.glob("decomp-*.jsonl")):
        for line in open(shard):
            o = json.loads(line)
            decomp[o["va"]] = o
    disasm = {}
    if (raw / "disasm.jsonl").exists():
        for line in open(raw / "disasm.jsonl"):
            o = json.loads(line)
            disasm[o["va"]] = o["asm"]

    groups = defaultdict(list)
    joined = []
    for g in ghidra:
        va = g["va"]
        grp = va[:4] + "0000"
        groups[grp].append((va, g))
        d = decomp.get(va)
        joined.append([
            va, g["size"], unwind.get(va, ""), g["name"], g["name_source"], grp, g["thunk"], g["instructions"],
            g["bytes_sha256"],
            "ok" if d and "c" in d else ("failed" if d else ("thunk" if g["thunk"] else "none")),
        ])

    # Only replace what this run actually produced: a missing stage must never wipe earlier results.
    if not decomp:
        print(f"{build}: no decompiler output in {raw}; keeping existing pseudocode/")
    for sub, have in (("pseudocode", bool(decomp)), ("disasm", bool(disasm))):
        if have:
            shutil.rmtree(out / sub, ignore_errors=True)
    for grp, items in groups.items():
        items.sort(key=lambda t: t[0])
        c_parts, a_parts = [], []
        for va, g in items:
            d = decomp.get(va)
            if d is not None:
                c_parts.append(f"// {va}  {g['name']}\n"
                               + (d.get("c") or f"// decompile failed: {d.get('error', '')}\n"))
            if va in disasm:
                a_parts.append(f"; {va}  {g['name']}\n" + disasm[va])
        for sub, parts, ext, have in (("pseudocode", c_parts, ".c", decomp), ("disasm", a_parts, ".asm", disasm)):
            if parts and have:
                path = out / sub / (grp + ext)
                path.parent.mkdir(parents=True, exist_ok=True)
                mark = "//" if ext == ".c" else ";"
                path.write_text(f"{mark} GENERATED by tools/ghidra/publish.py from build {build}. Do not edit.\n\n"
                                + "\n".join(parts))

    with open(out / "functions.tsv", "w", newline="\n") as f:
        f.write("va\tsize\tunwind_size\tname\tname_source\tblock\tthunk_of\tinstructions\tbytes_sha256\tdecompile\n")
        for r in sorted(joined):
            f.write("\t".join(str(x) for x in r) + "\n")

    ok = sum(1 for r in joined if r[-1] == "ok")
    failed = sum(1 for r in joined if r[-1] == "failed")
    named = sum(1 for r in joined if r[4] not in ("DEFAULT", "ANALYSIS"))
    summary = {"build": build, "functions": len(joined), "decompiled": ok, "decompile_failed": failed,
               "named_by_import_or_symbol": named, "blocks": len(groups),
               "code_bytes": sum(int(r[1]) for r in joined),
               "unwind_functions": len(unwind),
               "unwind_functions_missing": len(set(unwind) - {r[0] for r in joined})}
    (out / "summary.json").write_text(json.dumps(summary, indent=2) + "\n")
    print(json.dumps(summary))


if __name__ == "__main__":
    main()
